async function seedNotices() {
    for (const notice of notices) {
        const existing = await prisma.notice.findFirst({ where: { title: notice.title } });
        if (existing) {
            console.log(`이미 존재하여 건너뜁니다: ${notice.title}`);
            continue;
        }
        await prisma.notice.create({ data: notice });
        console.log(`생성 완료: ${notice.title}`);
    }
}

seedNotices()
    .then(() => console.log('✅ 공지사항 시드 완료!'))
    .catch((error) => {
        console.error('Error:', error);
        process.exitCode = 1;
    })
    .finally(async () => {
        await prisma.$disconnect();
    });
